// Ingredient icon when the name is recognised, otherwise the category icon, otherwise a package.
export function foodIconFor(name = '', category = '') {
  const text = name.trim().toLowerCase()
  const rule = INGREDIENT_RULES.find(([pattern]) => pattern.test(text))
  const key = rule?.[1] ?? CATEGORY_ICONS[category?.trim().toLowerCase()] ?? 'package'
  return FOOD_ICONS[key]
}
